def load_equipment_glossary(path: str | Path) -> dict[str, tuple[str, str, str]]:
    """`config/equipment_glossary.csv` -> {source_term: (lang, english, kind)}. Header-checked;
    kind must be one of GLOSSARY_KINDS."""
    out: dict[str, tuple[str, str, str]] = {}
    with open(path, encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(strip_comments(fh))
        check_header(reader.fieldnames, EQUIPMENT_GLOSSARY_FIELDS, path)
        for row in reader:
            term = (row.get("source_term") or "").strip()
            if not term or term.startswith("#"):
                continue
            kind = (row.get("kind") or "equipment").strip().lower()
            if kind not in GLOSSARY_KINDS:
                raise ValueError(f"{path}: kind must be one of {GLOSSARY_KINDS}, got {kind!r}")
            out[term] = (
                (row.get("lang") or "").strip().lower(),
                (row.get("english") or "").strip(),
                kind,
            )
    return out


def load_location_terms(path: str | Path) -> dict[str, str]:
    """`config/location_terms.csv` -> {term: canonical location}."""
    return _load_two_column_csv(path, LOCATION_TERMS_FIELDS)


def load_vessel_names(*paths: str | Path) -> frozenset[str]:
    """`config/vessel_names.txt` (+ `vessel_names_extra.txt`) -> casefolded names; a missing file
    is an empty list (the first is generated by scripts/build_lookup.py and may not exist on a
    fresh checkout; the second is hand-kept for sister ships the export never names)."""
    names = set()
    for path in paths:
        p = Path(path)
        if not p.exists():
            continue
        for line in strip_comments(p.read_text(encoding="utf-8").splitlines()):
            name = _RE_SPACE.sub(" ", line.strip()).casefold()
            if name:
                names.add(name)
    return frozenset(names)


@dataclass(frozen=True)
class ResolverConfig:
    """The shared tables both hygiene prompts need (docs/15 §4, docs/16 P0 / P1): loaded once per
    store from `config_dir`, read by the key functions and by the mint guard.

    `terms` is the derived match index for the symptom decomposition: lemmatised token tuple ->
    (kind ∈ component | location | modifier, canonical)."""

    config_dir: Path
    modifier_terms: Mapping[str, str]
    vessel_names: frozenset[str] = field(default_factory=frozenset)
    component_terms: Mapping[str, str] = field(default_factory=dict)
    location_terms: Mapping[str, str] = field(default_factory=dict)
    terms: Mapping[tuple[str, ...], tuple[str, str]] = field(default_factory=dict)
    qualifiers: Mapping[str, str] = field(default_factory=dict)
    glossary: Mapping[str, tuple[str, str, str]] = field(default_factory=dict)
    # P1b: HOW the failure is said and WHEN / HOW OFTEN it shows (docs/13 §8)
    phrases: Mapping[tuple[str, ...], tuple[str, ...]] = field(default_factory=dict)
    condition_terms: Mapping[str, str] = field(default_factory=dict)
    frequency_terms: Mapping[str, str] = field(default_factory=dict)
    head_nouns: Mapping[str, str] = field(default_factory=dict)


_WILD = "nwildcardn"  # survives _sym_tokens, which drops "<" and ">"


def _lemma_tokens(term: str) -> tuple[str, ...]:
    """A table row as the matcher sees it: lemmatised tokens; "<n>" stays a wildcard."""
    toks = _sym_tokens(term.replace("<n>", f" {_WILD} "))
    return tuple("<n>" if t == _WILD else _lemma(t) for t in toks)


def _lemma_bases() -> frozenset[str]:
    return _LEMMA_BASES


def _term_index(
    component: Mapping[str, str],
    location: Mapping[str, str],
    modifier: Mapping[str, str],
    condition: Mapping[str, str] | None = None,
    frequency: Mapping[str, str] | None = None,
) -> dict[tuple[str, ...], tuple[str, str]]:
    """Longest-first matching needs the terms as lemmatised token tuples. A term listed in two
    tables resolves in this precedence: component > location > modifier > condition > frequency."""
    index: dict[tuple[str, ...], tuple[str, str]] = {}
    for kind, table in (
        ("frequency", frequency or {}),
        ("condition", condition or {}),
        ("modifier", modifier),
        ("location", location),
        ("component", component),
    ):
        for term, canon in table.items():
            toks = _lemma_tokens(term)
            if toks:
                index[toks] = (kind, canon)
    return index


def load_config(config_dir: str | Path | None = None) -> ResolverConfig:
    """Read modifier_terms.csv (required: the build fails without it), component_terms.csv and
    location_terms.csv (optional, empty when missing) and vessel_names.txt (optional) from
    `config_dir`, default the repo's config/."""
    d = Path(config_dir) if config_dir is not None else DEFAULT_CONFIG_DIR
    terms = d / MODIFIER_TERMS_CSV
    if not terms.exists():
        raise FileNotFoundError(f"resolver config: {terms} is missing (config_dir={d})")
    modifiers = load_modifier_terms(terms)
    comp_path, loc_path = d / COMPONENT_TERMS_CSV, d / LOCATION_TERMS_CSV
    components = load_component_terms(comp_path) if comp_path.exists() else {}
    locations = load_location_terms(loc_path) if loc_path.exists() else {}
    qual_path, gloss_path = d / EQUIPMENT_QUALIFIERS_CSV, d / EQUIPMENT_GLOSSARY_CSV
    cond_path, freq_path = d / CONDITION_TERMS_CSV, d / FREQUENCY_TERMS_CSV
    phr_path, head_path = d / SYMPTOM_PHRASES_CSV, d / EQUIPMENT_HEAD_NOUNS_CSV
    conditions = load_condition_terms(cond_path) if cond_path.exists() else {}
    frequencies = load_frequency_terms(freq_path) if freq_path.exists() else {}
    phrases_raw = load_symptom_phrases(phr_path) if phr_path.exists() else {}
    phrases = {
        _lemma_tokens(k): _lemma_tokens(v) for k, v in phrases_raw.items() if _lemma_tokens(k)
    }
    return ResolverConfig(
        config_dir=d,
        modifier_terms=modifiers,
        vessel_names=load_vessel_names(d / VESSEL_NAMES_TXT, d / VESSEL_NAMES_EXTRA_TXT),
        component_terms=components,
        location_terms=locations,
        terms=_term_index(components, locations, modifiers, conditions, frequencies),
        qualifiers=load_equipment_qualifiers(qual_path) if qual_path.exists() else {},
        glossary=load_equipment_glossary(gloss_path) if gloss_path.exists() else {},
        phrases=phrases,
        condition_terms=conditions,
        frequency_terms=frequencies,
        head_nouns=load_equipment_head_nouns(head_path) if head_path.exists() else {},
    )


@dataclass(frozen=True)
class Cleaned:
    key: str
    position: str | None
    stem: str
    expanded: bool  # True when an abbreviation was expanded on the way to `key`
    parts: dict | None = None  # what the cleaner took apart (symptom: LabelParts.as_dict())

    @property
    def is_empty(self) -> bool:
        return not self.key


def _strip_position(raw: str, modifiers: Mapping[str, str]) -> tuple[str, list[str]]:
    """Remove position tokens from `raw` keeping its casing; return (stem, positions)."""
    positions: list[str] = []

    def numbered(m: re.Match) -> str:
        positions.append(f"No.{m.group(1) or m.group(2)}")
        return " "

    text = _RE_NUMBERED.sub(numbered, _RE_LEADING_QTY.sub("", raw, count=1))

    def unit(m: re.Match) -> str:
        if m.group(3):
            positions.append(_SIDE_LETTER[m.group(3).lower()])
        else:
            positions.append((m.group(1) + (m.group(2) or "")).upper())
        return " "

    text = _RE_UNIT.sub(unit, text)
    kept: list[str] = []
    for tok in _RE_SPACE.split(text.strip()):
        if not tok:
            continue
        bare = tok.strip(".,;:()[]/-&").lower()
        # "Port-side", "port/stbd": a token made only of modifier / noise words is one too
        bits = [b for b in re.split(r"[-/]", bare) if b]
        if bits and all(b in modifiers or b in NOISE_WORDS for b in bits):
            positions.extend(modifiers[b] for b in bits if b in modifiers)
        elif bare in NOISE_WORDS:
            continue
        else:
            kept.append(tok)
    stem = _RE_SPACE.sub(" ", " ".join(kept)).strip(" -:,;/")
    return stem, positions


def _expand(text: str) -> tuple[str, bool]:
    """Casefold, expand abbreviations, strip punctuation; return (key, expanded_anything)."""
    s = text.casefold().replace("&", " and ")
    expanded = False
    for abbr, full in PUNCTUATED_ABBREVIATIONS.items():
        pat = r"(?<![\w])" + re.escape(abbr) + r"(?![\w])"
        s, n = re.subn(pat, f" {full} ", s)
        expanded = expanded or n > 0
    s = _RE_PUNCT.sub(" ", s)
    out: list[str] = []
    for tok in s.split():
        if tok in ABBREVIATIONS:
            expanded = True
            if ABBREVIATIONS[tok]:
                out.append(ABBREVIATIONS[tok])
        else:
            out.append(_singular(tok))
    return _RE_SPACE.sub(" ", " ".join(out)).strip(), expanded


def _singular(tok: str) -> str:
    """Fold plurals into the key: "safety valves" and "safety valve" are one part. Crude on
    purpose (the key is a join key, not the shown name): -ies -> -y, trailing -s dropped unless
    the word ends in -ss / -us / -is or is short. Digits and codes are left alone."""
    if not tok.isalpha() or len(tok) <= 3:
        return tok
    if tok.endswith("ies"):
        return tok[:-3] + "y"
    if tok.endswith("s") and not tok.endswith(("ss", "us", "is")):
        return tok[:-1]
    return tok


def _default_config() -> ResolverConfig:
    return DEFAULT_CONFIG


def normalize(raw: str | None, config: ResolverConfig | None = None) -> Cleaned:
    """Clean one extracted name with no record context (the `part` steps of
    `clean_equipment_label`: glossary, abbreviations, position, qualifiers). Deterministic; see
    module docstring. `config` supplies the tables (default: the repo's config/)."""
    return _cleaned(clean_equipment_label(raw, None, config, kind="part"))


def has_abbreviations(text: str) -> bool:
    """True when `text` would change under abbreviation expansion (so it is not display-ready)."""
    return _expand(text)[1]


