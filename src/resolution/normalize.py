"""
Rule-based cleaning of component / equipment names and symptom wordings (02 §3.9, first stage of
the cascade).

`normalize(raw)` turns a name as extracted ("No. 3 AE", "M/E C.W. P/P", "HFO storage tank 1S")
into

  key       deterministic standard key: casefolded, punctuation stripped, abbreviations expanded,
            position tokens removed -> "auxiliary engine", "main engine cooling water pump",
            "heavy fuel oil storage tank"
  position  the tokens that said WHICH one -> "No.3", "1S", "port forward" (or None)
  stem      the raw text with the position tokens removed, original casing kept. Used by the
            display-name view: the longest stem among a standard's aliases that contains no
            abbreviation is what the UI shows.
  parts     optional dict of what the cleaner took apart (None for equipment / part today; the
            decomposed label for a symptom). The store keeps it on the alias row (alias.parts) and
            the mint guard reads it (docs/13 §4).

The key is a function of the text alone, so two spellings of one part converge on the same
standard whichever arrives first, and two corpora processed in different orders mint the same
vocabulary. Equipment TYPE and position are kept apart on purpose: the v2 record already has
`equipment_type` and `position` as separate fields, and "No.1 pump" / "No.2 pump" are one type.

`clean_equipment_label(label, context)` is the equipment / part cleaner that runs BEFORE the
key is taken (docs/13 §3, decided in docs/15 §6): it strips what the v2 record already carries as
separate fields — a fleet vessel name (`config/vessel_names.txt` + `vessel_names_extra.txt`),
non-Latin words through `config/equipment_glossary.csv`, the record entry's own maker / model /
serial, condition words from `config/equipment_qualifiers.csv` — and records every removal in
`EquipmentParts.stripped` (-> alias.parts) with the step names in the log chain. Nothing is
extracted into new storage: the record is the occurrence. A label that still carries a vessel
name, a position token, non-Latin text or an identifier after cleaning is refused by the mint
guard (`lookup.equipment_guard`), never minted.

`decompose_symptom(label, equipment_type)` is the symptom kind's key function (docs/13 §8,
decision A1 in docs/15 §3): a symptom standard is the FAILURE MODE only. The component, the
location and the side / position modifiers are structured data on the alias row, not words in
the key; the component is resolved as the existing kind="part" so "knocking from exhaust valve"
and "renew exhaust valve" meet on one standard id. Component nouns therefore LEAVE the key; the
earlier rule that kept them ("they localise the symptom") is withdrawn with A1.

Everything here is a table, not code: extend ABBREVIATIONS as the corpus shows new ones. The
position / side words live in `config/modifier_terms.csv` (term, canonical; left -> port,
right -> starboard), the component nouns in `config/component_terms.csv`, the places in
`config/location_terms.csv`, the non-Latin equipment words in `config/equipment_glossary.csv`,
the condition words in `config/equipment_qualifiers.csv`, and the fleet's vessel names in
`config/vessel_names.txt` (generated by scripts/build_lookup.py) + `vessel_names_extra.txt`
(hand-kept sister ships); all are read by `load_config()` into a `ResolverConfig`
that `LookupStore(config_dir=...)` passes down. Every config CSV is header-checked at load: a
wrong header raises ValueError and the build fails rather than silently reading nothing.

Nothing here is fuzzy. A name the rules do not recognise is minted as a new standard with status
"auto" and shows up in the review queue (lookup.review_queue), unless the store's mint guard
refuses it into `pending_term`; the embedding and LLM-adjudicator stages of 02 §3.9 sit AFTER
this table, not inside it.
"""

