# `clean_equipment_label()` runs before the key is taken (docs/13 §3, docs/15 §6). Steps, each a
# name in the log chain when it changed the text:
#
#   a. vessel_strip   a fleet vessel name (config/vessel_names.txt + vessel_names_extra.txt), whole
#                     name only, written with spaces, hyphens or run together ("PACIFIC GARNET",
#                     "Pacific-Garnet", "PACIFICGARNET"); never a substring ("ENGINE STAR" does not
#                     touch "engine"). A name that is not the record's own vessel is a sister ship:
#                     EquipmentParts.sister_vessel, and the store logs it.           equipment only
#   b. glossary       when the label has non-Latin script: "N号" -> "No.N", then longest-first
#                     replacement from config/equipment_glossary.csv; script = lang. Non-Latin text
#                     left over goes to the adjudicator (injected Callable[[str], str | None]) if
#                     there is one, else stays as `untranslated` -> guard: needs_translation
#   e. record_strip   whole-phrase matches of the record entry's maker / model / serial (as written
#                     and casefolded / punctuation-stripped); "NA" and blanks skipped equipment only
#   f. qualifier      condition words from config/equipment_qualifiers.csv -> stripped["qualifier"]
#   d. position       _strip_position: numbered units, 1S / (P), the modifier table (left -> port)
#   c. abbreviations  _expand: PUNCTUATED_ABBREVIATIONS, ABBREVIATIONS, _singular -> the key
#
# e / f run on the raw tokens before the abbreviation expansion so that a maker written "MAN B&W"
# is matched as written; the chain lists the steps in the order they fired. Everything removed is
# kept in `stripped[step]`; `residue` is what a regex (not a table) dropped: the leading quantity.
# `issues` is what the mint guard reads: contains_vessel | contains_position | needs_translation |
# contains_identifier, for anything the cleaning did not get out of the core.

_RE_CJK_NO = re.compile(r"(\d{1,3})\s*[号호]")
_RE_LATIN_WORD = re.compile(r"[A-Za-z]")


def is_non_latin(ch: str) -> bool:
    """An alphabetic character outside the Latin script (CJK, Hangul, Cyrillic, Greek, ...)."""
    if not ch.isalpha() or ord(ch) < 0x250:
        return False
    return not unicodedata.name(ch, "").startswith("LATIN")


def has_non_latin(text: str) -> bool:
    return any(is_non_latin(ch) for ch in text)


def _non_latin_runs(text: str) -> list[str]:
    """The whitespace-delimited tokens of `text` that still carry non-Latin letters."""
    return [t for t in text.split() if has_non_latin(t)]


def _vessel_patterns(names: Iterable[str]) -> list[tuple[str, re.Pattern]]:
    """Whole-name patterns, longest first: words may be joined by spaces, hyphens or nothing."""
    out = []
    for name in sorted(names, key=len, reverse=True):
        words = [re.escape(w) for w in name.split()]
        if not words:
            continue
        out.append(
            (name, re.compile(r"(?<!\w)" + r"[\s\-]*".join(words) + r"(?!\w)", re.IGNORECASE))
        )
    return out


def _identifier_forms(value: str | None) -> list[str]:
    """The forms a maker / model / serial may take inside a label: as written, casefolded,
    punctuation-stripped. "NA", "N/A", "-" and blanks give nothing."""
    v = (value or "").strip()
    if not v or v.upper() in ("NA", "N/A", "NONE", "-", "UNKNOWN"):
        return []
    forms = {v, v.casefold(), _RE_SPACE.sub(" ", _RE_PUNCT.sub(" ", v.casefold())).strip()}
    return sorted((f for f in forms if f), key=len, reverse=True)


@dataclass(frozen=True)
class EquipmentParts:
    core: str  # the key: what remains, casefolded, abbreviations expanded
    position: str | None  # every position token in reading order: "No.1", "port forward"
    side: str | None  # the port / starboard part of it, on its own
    stripped: dict  # step -> removed text
    script: str | None  # lang of the glossary terms matched (zh / ja / ko)
    residue: tuple[str, ...]  # dropped by a regex, not a table
    stem: str = ""  # cleaned text with its casing, position removed: the display candidate
    expanded: bool = False
    vessel: str | None = None  # fleet name the label carried
    sister_vessel: str | None = None  # ... when it is not the record's own vessel
    untranslated: str | None = None  # non-Latin text no table / adjudicator resolved
    steps: tuple[str, ...] = ()
    issues: tuple[str, ...] = ()  # guard reasons

    def as_dict(self) -> dict:
        d: dict = {"core": self.core}
        for k in ("position", "side", "script", "vessel", "sister_vessel", "untranslated"):
            v = getattr(self, k)
            if v:
                d[k] = v
        if self.stripped:
            d["stripped"] = dict(self.stripped)
        for k in ("residue", "steps", "issues"):
            v = getattr(self, k)
            if v:
                d[k] = list(v)
        return d


def clean_equipment_label(
    label: str | None,
    context: Mapping[str, str | None] | None = None,
    config: ResolverConfig | None = None,
    kind: str = "equipment",
    adjudicator: Callable[[str], str | None] | None = None,
) -> EquipmentParts:
    """Take an equipment (or part) name apart; see the section comment above. `context` is the
    record entry (`vessel_name`, `maker`, `model`, `serial`); a part has none and skips the
    vessel and record steps."""
    if not label or not label.strip():
        return EquipmentParts("", None, None, {}, None, ())
    cfg = config or _default_config()
    ctx = context or {}
    text = _RE_SPACE.sub(" ", label.strip())
    stripped: dict[str, str] = {}
    steps: list[str] = []
    residue: list[str] = []
    vessel = sister = script = untranslated = None

    # a. vessel strip (equipment only)
    if kind == "equipment" and cfg.vessel_names:
        for name, pat in _vessel_patterns(cfg.vessel_names):
            m = pat.search(text)
            if m:
                vessel = name
                stripped["vessel"] = m.group()
                text = (text[: m.start()] + " " + text[m.end() :]).strip()
                steps.append("vessel_strip")
                own = (ctx.get("vessel_name") or "").casefold()
                if own and _RE_SPACE.sub(" ", own) != name:
                    sister = name
                break

    # b. glossary (any kind)
    if has_non_latin(text):
        before = text
        text = _RE_CJK_NO.sub(r" No.\1 ", text)
        for term in sorted(cfg.glossary, key=len, reverse=True):
            if term in text:
                lang, english, _gkind = cfg.glossary[term]
                text = text.replace(term, f" {english} ")
                script = script or lang
        text = _RE_SPACE.sub(" ", text).strip()
        if text != before:
            stripped["glossary"] = before
            steps.append("glossary")
        if has_non_latin(text):
            leftover = " ".join(_non_latin_runs(text))
            translated = adjudicator(leftover) if adjudicator and leftover else None
            if translated:
                for run in _non_latin_runs(text):
                    text = text.replace(run, " ", 1)
                text = _RE_SPACE.sub(" ", f"{text} {translated}").strip()
                stripped["adjudicator"] = leftover
                steps.append("adjudicator")
            else:
                untranslated = leftover
                script = script or "unknown"

    # e. record strip (equipment only): maker / model / serial as written in the record entry
    if kind == "equipment":
        removed = []
        for field_name in ("maker", "model", "serial"):
            for form in _identifier_forms(ctx.get(field_name)):
                pat = re.compile(r"(?<!\w)" + re.escape(form) + r"(?!\w)", re.IGNORECASE)
                m = pat.search(text)
                if m:
                    removed.append(m.group())
                    text = (text[: m.start()] + " " + text[m.end() :]).strip()
                    break
        if removed:
            stripped["record"] = " | ".join(removed)
            steps.append("record_strip")
    text = _RE_SPACE.sub(" ", text).strip(" -:,;/")

    # f. qualifiers (any kind)
    if cfg.qualifiers:
        kept, quals = [], []
        for tok in text.split():
            bare = tok.strip(".,;:()[]/-&").casefold()
            if bare in cfg.qualifiers:
                quals.append(cfg.qualifiers[bare])
            else:
                kept.append(tok)
        if quals:
            stripped["qualifier"] = " ".join(quals)
            steps.append("qualifier")
            text = " ".join(kept)

    # d. position, c. abbreviations
    qty = _RE_LEADING_QTY.match(text)
    if qty and qty.group().strip():
        residue.append(qty.group().strip())
    stem, positions = _strip_position(text, cfg.modifier_terms)
    if positions:
        steps.append("position")
    key, expanded = _expand(stem)
    if expanded:
        steps.append("abbreviations")
    sides = [p for p in positions if p in ("port", "starboard")]

    # what the guard reads
    issues: list[str] = []
    if kind == "equipment":
        for name, pat in _vessel_patterns(cfg.vessel_names):
            if pat.search(key):
                issues.append("contains_vessel")
                break
    if any(tok in cfg.modifier_terms for tok in key.split()) or _RE_NUMBERED.search(key):
        issues.append("contains_position")
    if untranslated or has_non_latin(key):
        issues.append("needs_translation")
    if kind == "equipment":
        for field_name in ("maker", "model", "serial"):
            forms = _identifier_forms(ctx.get(field_name))
            if any(
                re.search(r"(?<!\w)" + re.escape(f) + r"(?!\w)", key, re.IGNORECASE) for f in forms
            ):
                issues.append("contains_identifier")
                break
    return EquipmentParts(
        core=key,
        position=" ".join(dict.fromkeys(positions)) or None,
        side=" ".join(dict.fromkeys(sides)) or None,
        stripped=stripped,
        script=script,
        residue=tuple(residue),
        stem=stem,
        expanded=expanded,
        vessel=vessel,
        sister_vessel=sister,
        untranslated=untranslated,
        steps=tuple(steps),
        issues=tuple(dict.fromkeys(issues)),
    )


def _cleaned(ep: EquipmentParts, with_parts: bool = False) -> Cleaned:
    """EquipmentParts -> the Cleaned the store works with."""
    if not ep.core and not ep.position and not ep.untranslated:
        return Cleaned(key="", position=None, stem="", expanded=False)
    return Cleaned(
        key=ep.core,
        position=ep.position,
        stem=ep.stem,
        expanded=ep.expanded,
        parts=ep.as_dict() if with_parts else None,
    )


# --------------------------------------------------------------------------- symptoms
# Symptom wording (faults[].symptom): `decompose_symptom()` is the key function of the resolver's
# "symptom" kind (docs/13 §8, A1). It takes a label apart into
#
#   core        the failure mode -> the standard key ("knocking sound", "water leak")
#   component   the part it sits ON, as a canonical part key ("exhaust valve"); resolved by the
#               store as kind="part" so it shares the id of action_logs[].parts[]
#   location    WHERE, from config/location_terms.csv ("pump room")
#   modifiers   side / position words from config/modifier_terms.csv ("starboard")
#   position    the unit tokens _SYM_POSITION_RE found ("cylinder no.5")
#   residue     words of an unmatched prepositional tail: candidates for the tables
#   leftover    table terms still inside the core: the label did not decompose cleanly and the
#               mint guard queues it (reason undecomposed) instead of minting a standard
#
# Order: lemma map (explicit domain map + _singular, never a stemmer) -> vessel-name strip
# (whole fleet name) -> position (_SYM_POSITION_RE) -> term extraction, patterns tried in order:
#   (a) tail   `<core> <prep> <term…>`: the tokens after the LAST preposition up to the end of
#              the clause (a comma / semicolon ends a clause) must all be table terms, articles
#              or the record's equipment words; an unmatched tail stays in the core and its
#              unknown words go to `residue`, and its terms are NOT pulled out by (c)
#   (b) head   `<term…> <core>`: table terms at the start of the label
#   (c) bare   a table term anywhere else: fills an empty slot, else stays (-> leftover)
# -> equipment-type strip (ONLY the record's own equipment_type words and their abbreviations)
# -> core, with orphaned function words dropped and _SYM_TRAIL_RE applied last.
# A run of adjacent component terms ("fuel pump spring", "cylinder head water jacket") is ONE
# component phrase: splitting it would put a component noun back into the key. A label whose
# core would be empty (the label is only a component) passes through whole instead.

_SYM_POSITION_RE = re.compile(
    r"\b(?:cyl(?:inder)?s?|units?)\b(?:\s*(?:no\.?|nos\.?|number|#))?\s*[.:]?\s*#?\s*\d+[a-z]?\b"
    r"|\b(?:no\.?|nos\.?|number|#)\s*:?\s*\d+[a-z]?\b|#\s*\d+\b|\b\d+\s*(?:st|nd|rd|th)\b",
    re.IGNORECASE,
)
_SYM_PUNCT_RE = re.compile(r"[^\w\s/]")
_SYM_HYPHEN_RE = re.compile(r"[-‐-―]")
_SYM_TRAIL_RE = re.compile(r"\s+(?:from|on|at|in|of|for|to|the|a|an)$", re.IGNORECASE)

# the small explicit domain map; everything else is `_singular`. A stemmer is NOT acceptable
# (it would fold "bearing" into "bear" and "casing" into "case").
LEMMA_MAP: dict[str, str] = {
    # the explicit past / -ing / 3rd-person forms of every verb here (P1b); "fails" and the other
    # plain -s forms already fold through _singular. A form NOT listed stays as written and is
    # reported as residue (unmapped_inflection); never a stemmer.
    "leaking": "leak",
    "leaked": "leak",
    "leaks": "leak",
    "cracked": "crack",
    "cracking": "crack",
    "cracks": "crack",
    "broken": "break",
    "broke": "break",
    "breaking": "break",
    "breaks": "break",
    "tripped": "trip",
    "tripping": "trip",
    "trips": "trip",
    "fractured": "fracture",
    "fracturing": "fracture",
    "fractures": "fracture",
    "failed": "fail",
    "failing": "fail",
    "fails": "fail",
    "activated": "activate",
    "activating": "activate",
    "activates": "activate",
    "operated": "operate",
    "operating": "operate",
    "operates": "operate",
    "stopped": "stop",
    "stopping": "stop",
    "stops": "stop",
    "started": "start",
    "starting": "start",
    "starts": "start",
    "flooded": "flood",
    "flooding": "flood",
    "floods": "flood",
    "chipped": "chip",
    "chipping": "chip",
    "chips": "chip",
    "alarmed": "alarm",
    "alarming": "alarm",
    "alarms": "alarm",
    "imposed": "impose",
    "imposing": "impose",
    "imposes": "impose",
    "stabilized": "stabilize",
    "stabilised": "stabilize",
    "stabilizing": "stabilize",
    "stabilizes": "stabilize",
}
_LEMMA_BASES = frozenset(LEMMA_MAP.values())
# the "where" prepositions open a located tail; the "when" ones (P1b) open a condition tail —
# an unknown tail after any of them stays in the core and reaches residue
SYMPTOM_PREPOSITIONS = frozenset(
    {
        "from", "at", "on", "in", "of", "around", "inside", "below", "above", "into",
        "during", "while", "when", "after", "before", "since",
    }
)  # fmt: skip
_ARTICLES = frozenset({"the", "a", "an"})
# function words a removed span can leave stranded ("into the from a hole" -> "from a hole")
_FUNCTION_WORDS = SYMPTOM_PREPOSITIONS | _ARTICLES | {"for", "to", "with", "by", "and", "or"}
# never a candidate term: what an unmatched tail is allowed to contain without being reported
_RESIDUE_STOP = _FUNCTION_WORDS | {
    "is", "are", "was", "were", "be", "been", "being", "has", "have", "had", "not", "no",
    "as", "that", "this", "these", "those", "it", "its", "than", "then", "also", "later",
    "which", "who", "due", "only", "still", "very", "some", "all", "about", "found",
}  # fmt: skip


def unmapped_inflection(tok: str) -> str | None:
    """The LEMMA_MAP base `tok` looks like an inflection of, when that form is NOT in the map:
    "surging" for a base "surge" nobody listed. Such a token stays as written in the core, is
    reported as residue and makes the label undecomposed for the guard. None otherwise."""
    if tok in LEMMA_MAP or tok in _LEMMA_BASES or not tok.isalpha():
        return None
    cands = []
    if tok.endswith("ed"):
        cands += [tok[:-2], tok[:-1], tok[:-3] if len(tok) > 4 and tok[-3] == tok[-4] else ""]
    if tok.endswith("ing"):
        cands += [tok[:-3], tok[:-3] + "e", tok[:-4] if len(tok) > 5 and tok[-4] == tok[-5] else ""]
    if tok.endswith("s") and not tok.endswith("ss"):
        cands += [tok[:-1], tok[:-2] if tok.endswith("es") else ""]
    for c in cands:
        if c and c in _LEMMA_BASES and _singular(tok) != c:
            return c
    return None


@dataclass(frozen=True)
class LabelParts:
    core: str
    component: str | None  # canonical part key
    location: str | None
    modifiers: tuple[str, ...]
    position: str | None
    residue: tuple[str, ...]
    stem: str = ""  # the core with the label's casing, for display_name()
    component_raw: str | None = None  # the component as spelled in the label
    vessel: str | None = None  # a fleet vessel name the label carried
    steps: tuple[str, ...] = ()  # the cleaning steps that changed the text (-> log chain)
    leftover: tuple[str, ...] = ()  # table terms still in the core -> guard: undecomposed
    condition: str | None = None  # WHEN: canonical from config/condition_terms.csv (P1b)
    frequency: str | None = None  # HOW OFTEN: canonical from config/frequency_terms.csv (P1b)
    head_noun: str | None = None  # the bare equipment head noun stripped from the core (P1b)
    phrases: tuple[str, ...] = ()  # the verb phrases canonicalised in the core (P1b)

    def as_dict(self) -> dict:
        """What goes on the alias row (alias.parts): the non-empty fields, lists as lists."""
        d: dict = {"core": self.core}
        for k in (
            "component",
            "component_raw",
            "location",
            "position",
            "vessel",
            "condition",
            "frequency",
            "head_noun",
        ):
            v = getattr(self, k)
            if v:
                d[k] = v
        if self.phrases:
            d["phrases"] = list(self.phrases)
        for k in ("modifiers", "residue", "steps", "leftover"):
            v = getattr(self, k)
            if v:
                d[k] = list(v)
        return d


def _lemma(tok: str) -> str:
    return LEMMA_MAP.get(tok) or _singular(tok)


def _sym_tokens(text: str) -> list[str]:
    """Lowercase word tokens of a label: hyphens are spaces, '/' stays inside a token
    ("high/low"), every other punctuation goes."""
    t = _SYM_HYPHEN_RE.sub(" ", text.lower())
    t = _SYM_PUNCT_RE.sub(" ", t)
    return t.split()


def head_noun_of(equipment_type: str | None, config: ResolverConfig | None = None) -> str | None:
    """The bare head noun of a record's equipment_type from config/equipment_head_nouns.csv
    ("engine" for main_engine); None when the table has no row. Explicit rows only."""
    if not equipment_type:
        return None
    cfg = config or _default_config()
    return cfg.head_nouns.get(equipment_type.strip().lower()) or None


def equipment_forms(equipment_type: str | None) -> list[tuple[str, ...]]:
    """The word forms of a record's equipment_type that a symptom wording may carry:
    'main_engine' -> ('main', 'engine'), ('m/e',), ('m', 'e'), ('me',). Only the record's OWN type;
    nothing generic (docs/15 §2: the generic list ate component nouns)."""
    if not equipment_type:
        return []
    phrase = " ".join(equipment_type.strip().lower().replace("_", " ").split())
    if not phrase:
        return []
    forms: set[tuple[str, ...]] = {tuple(phrase.split())}
    for table in (PUNCTUATED_ABBREVIATIONS, ABBREVIATIONS):
        for abbr, full in table.items():
            if full == phrase:
                forms.add(tuple(_sym_tokens(abbr)) or (abbr,))
                forms.add((abbr,))
    return sorted((f for f in forms if f), key=len, reverse=True)


@dataclass
class _Tok:
    orig: str
    lem: str
    end_clause: bool = False  # the original token ended with , or ;
    eq: bool = False  # part of an equipment-type form (transparent, stripped at the end)
    removed: bool = False  # extracted (term / vessel / stranded function word)
    in_failed_tail: bool = False  # inside an unmatched prepositional tail


def decompose_symptom(
    label: str | None, equipment_type: str | None = None, config: ResolverConfig | None = None
) -> LabelParts:
    """Take a symptom wording apart; see the section comment above for the rules."""
    if not label or not label.strip():
        return LabelParts("", None, None, (), None, ())
    cfg = config or _default_config()
    steps: list[str] = []

    # 1. position tokens (the regex works on the raw text)
    positions = [" ".join(m.group().lower().split()) for m in _SYM_POSITION_RE.finditer(label)]
    text = _SYM_POSITION_RE.sub(" ", label)
    if positions:
        steps.append("position")

    # 2. tokens: original casing + lemma, clause boundaries kept
    toks: list[_Tok] = []
    for raw_tok in _SYM_HYPHEN_RE.sub(" ", text).split():
        end = raw_tok.endswith((",", ";", ":"))
        words = _SYM_PUNCT_RE.sub(" ", raw_tok).split()
        for i, w in enumerate(words):
            # an acronym written in capitals (EGCS, RPM, LO) is not a plural
            lem = w.lower() if (w.isupper() and len(w) > 1) else _lemma(w.lower())
            toks.append(_Tok(orig=w, lem=lem, end_clause=end and i == len(words) - 1))
        if end and words or end and toks:
            toks[-1].end_clause = True
    if not toks:
        return LabelParts("", None, None, (), " ".join(positions) or None, ())
    lowers = [t.orig.lower() for t in toks]

    # 3. vessel-name strip (whole name, any position)
    vessel = None
    for name in sorted(cfg.vessel_names, key=len, reverse=True):
        words = name.split()
        n = len(words)
        for i in range(len(lowers) - n + 1):
            if lowers[i : i + n] == words and not any(t.removed for t in toks[i : i + n]):
                for t in toks[i : i + n]:
                    t.removed = True
                vessel = name
        if vessel:
            steps.append("vessel_strip")
            break

    # 4. the record's equipment words: transparent during matching, stripped at the end
    for form in equipment_forms(equipment_type):
        n = len(form)
        for i in range(len(lowers) - n + 1):
            if tuple(lowers[i : i + n]) == form and not any(
                t.removed or t.eq for t in toks[i : i + n]
            ):
                for t in toks[i : i + n]:
                    t.eq = True
    if any(t.eq for t in toks):
        steps.append("equipment_strip")

    # 5. term extraction
    live = [i for i, t in enumerate(toks) if not t.removed and not t.eq]
    component: str | None = None
    component_raw: str | None = None
    location: str | None = None
    condition: str | None = None
    frequency: str | None = None
    modifiers: list[str] = []
    residue: list[str] = []
    max_len = max((len(k) for k in cfg.terms), default=0)
    wild = [(k, v) for k, v in cfg.terms.items() if "<n>" in k]

    def match_at(seq: list[int], j: int) -> tuple[int, str, str] | None:
        """Longest term starting at seq[j]; (n_tokens, kind, canonical) or None. A "<n>" in a
        table row matches one number and is carried into the canonical ("above 80 rpm")."""
        for n in range(min(max_len, len(seq) - j), 0, -1):
            key = tuple(toks[k].lem for k in seq[j : j + n])
            hit = cfg.terms.get(key)
            if hit:
                return n, hit[0], hit[1]
            for pat, (kind, canon) in wild:
                if len(pat) == n and all(
                    (p == "<n>" and t.isdigit()) or p == t for p, t in zip(pat, key)
                ):
                    num = next(t for p, t in zip(pat, key) if p == "<n>")
                    return n, kind, canon.replace("<n>", num)
        return None

    def take(kind: str, canon: str, idxs: list[int]) -> bool:
        """Fill a slot; True when the term was extracted (and must leave the core)."""
        nonlocal component, component_raw, location, condition, frequency
        if kind == "modifier":
            if canon not in modifiers:
                modifiers.append(canon)
            return True
        if kind == "location":
            if location is None:
                location = canon
                return True
            return False
        if kind == "condition":
            if condition is None:
                condition = canon
                return True
            return False
        if kind == "frequency":
            if frequency is None:
                frequency = canon
                return True
            return False
        if component is None:
            component = canon
            component_raw = " ".join(toks[k].orig for k in idxs)
            return True
        return False

    def extract_run(seq: list[int]) -> bool:
        """`seq` is all terms (or articles). Adjacent component terms are one phrase."""
        j = 0
        runs: list[tuple[str, str, list[int]]] = []
        while j < len(seq):
            if toks[seq[j]].lem in _ARTICLES:
                j += 1
                continue
            m = match_at(seq, j)
            if not m:
                return False
            n, kind, canon = m
            idxs = seq[j : j + n]
            if kind == "component" and runs and runs[-1][0] == "component":
                prev = runs[-1]
                joined_idx = prev[2] + idxs
                joined = " ".join(toks[k].orig for k in joined_idx)
                runs[-1] = ("component", normalize(joined, cfg).key or canon, joined_idx)
            else:
                runs.append((kind, canon, idxs))
            j += n
        if not runs:
            return False
        for kind, canon, idxs in runs:
            if take(kind, canon, idxs):
                for k in idxs:
                    toks[k].removed = True
            # an unfilled slot's term stays in the core (-> leftover)
        for k in seq:  # articles of a matched run go too
            if toks[k].lem in _ARTICLES:
                toks[k].removed = True
        return True

    # (a) tail after the last preposition, to the end of its clause
    preps = [i for i in live if toks[i].lem in SYMPTOM_PREPOSITIONS]
    if preps:
        p = preps[-1]
        tail: list[int] = []
        for i in live:
            if i <= p:
                continue
            tail.append(i)
            if toks[i].end_clause:
                break
        if not tail:
            toks[p].removed = True  # dangling preposition left by a removed position
        elif extract_run([p, *tail]):
            steps.append("tail")  # the preposition is part of the term ("in port", "above 80 rpm")
        elif extract_run(tail):
            toks[p].removed = True
            steps.append("tail")
        else:
            covered: set[int] = set()  # tail tokens that ARE table terms are not candidates
            j = 0
            while j < len(tail):
                m = match_at(tail, j)
                if m:
                    covered.update(tail[j : j + m[0]])
                    j += m[0]
                else:
                    j += 1
            for i in tail:
                toks[i].in_failed_tail = True
                if i not in covered and toks[i].lem not in _RESIDUE_STOP and toks[i].lem.isalpha():
                    residue.append(toks[i].lem)
    # (b) head: leading terms
    live = [i for i, t in enumerate(toks) if not t.removed and not t.eq]
    if live:
        head: list[int] = []
        j = 0
        while j < len(live):
            if toks[live[j]].lem in _ARTICLES:
                head.append(live[j])
                j += 1
                continue
            m = match_at(live, j)
            if not m or toks[live[j]].in_failed_tail:
                break
            head.extend(live[j : j + m[0]])
            j += m[0]
        if head and any(toks[k].lem not in _ARTICLES for k in head) and extract_run(head):
            steps.append("head")
    # (c) bare terms anywhere else (not inside an unmatched tail)
    live = [i for i, t in enumerate(toks) if not t.removed and not t.eq]
    j = 0
    while j < len(live):
        if toks[live[j]].in_failed_tail:
            j += 1
            continue
        m = match_at(live, j)
        if m:
            n, kind, canon = m
            idxs = live[j : j + n]
            if take(kind, canon, idxs):
                for k in idxs:
                    toks[k].removed = True
                if "bare" not in steps:
                    steps.append("bare")
            j += n
        else:
            j += 1
    # (d) the bare head noun of the record's equipment ("engine" on a main_engine record) is the
    # equipment, unless a component / location term already claimed the word ("engine room")
    head_noun = None
    hn = head_noun_of(equipment_type, cfg)
    if hn:
        for t in toks:
            if not t.removed and not t.eq and (t.lem == hn or t.orig.lower() == hn):
                t.eq = True
                head_noun = hn
        if head_noun:
            steps.append("head_noun")
    if component:
        steps.append("component")
    if location:
        steps.append("location")
    if modifiers:
        steps.append("modifier")
    if condition:
        steps.append("condition")
    if frequency:
        steps.append("frequency")

    # 6. the core: drop extracted / equipment tokens and stranded function words
    core_idx = [i for i, t in enumerate(toks) if not t.removed and not t.eq]
    changed = True
    while changed and core_idx:
        changed = False
        if toks[core_idx[0]].lem in _FUNCTION_WORDS:
            core_idx.pop(0)
            changed = True
            continue
        if toks[core_idx[-1]].lem in _FUNCTION_WORDS:
            core_idx.pop()
            changed = True
            continue
        kept = set(core_idx)
        for a in core_idx:
            # a preposition / article whose object was extracted is stranded: its next token in
            # the ORIGINAL label is no longer in the core ("into the pump room" -> "into the")
            if toks[a].lem in SYMPTOM_PREPOSITIONS | _ARTICLES and (a + 1) not in kept:
                core_idx.remove(a)
                changed = True
                break
    if not core_idx and (component or location or modifiers or condition or frequency):
        # the label is only a component / place / circumstance: no failure mode left -> whole
        core_idx = [i for i, t in enumerate(toks) if not t.eq and not (vessel and t.removed)]
        component = component_raw = location = condition = frequency = None
        modifiers = []
        steps = [s for s in steps if s in ("position", "vessel_strip", "equipment_strip")]
        steps.append("whole")
    core_lems = [toks[i].lem for i in core_idx]
    core_origs = [toks[i].orig for i in core_idx]

    # 6b. HOW it is said: verb-phrase canonicalisation on the core (config/symptom_phrases.csv),
    # longest-first, whole-word; the display stem takes the canonical words for the span
    phrases_hit: list[str] = []
    if cfg.phrases:
        pmax = max(len(k) for k in cfg.phrases)
        out_l: list[str] = []
        out_o: list[str] = []
        j = 0
        while j < len(core_lems):
            hit = None
            for n in range(min(pmax, len(core_lems) - j), 0, -1):
                canon = cfg.phrases.get(tuple(core_lems[j : j + n]))
                if canon is not None:
                    hit = (n, canon)
                    break
            if hit:
                n, canon = hit
                if list(canon) != core_lems[j : j + n]:
                    phrases_hit.append(" ".join(core_lems[j : j + n]))
                out_l.extend(canon)
                out_o.extend(canon)  # the display stem says it the canonical way too
                j += n
            else:
                out_l.append(core_lems[j])
                out_o.append(core_origs[j])
                j += 1
        core_lems, core_origs = out_l, out_o
        if phrases_hit:
            steps.append("phrase")
    core = _SYM_TRAIL_RE.sub("", " ".join(core_lems))
    stem = _SYM_TRAIL_RE.sub("", " ".join(core_origs))
    core_lems = core.split()

    # 7. what the guard reads: table terms, phrase rows and unmapped verb forms the core still
    # carries (a canonical phrase that maps to itself is not a leftover)
    leftover: list[str] = []
    j = 0
    while j < len(core_lems):
        hit = None
        for n in range(min(max(max_len, 1), len(core_lems) - j), 0, -1):
            key = tuple(core_lems[j : j + n])
            t = cfg.terms.get(key)
            if t:
                leftover.append(t[1])
                hit = n
                break
            canon = cfg.phrases.get(key)
            if canon is not None and list(canon) != list(key):
                leftover.append(" ".join(key))
                hit = n
                break
        if hit:
            j += hit
            continue
        base = unmapped_inflection(core_lems[j])
        if base:
            leftover.append(core_lems[j])
            if core_lems[j] not in residue:
                residue.append(core_lems[j])
        j += 1

    return LabelParts(
        core=core,
        component=component,
        location=location,
        modifiers=tuple(modifiers),
        position=" ".join(dict.fromkeys(positions)) or None,
        residue=tuple(dict.fromkeys(residue)),
        stem=stem,
        component_raw=component_raw,
        vessel=vessel,
        steps=tuple(dict.fromkeys(steps)),
        leftover=tuple(leftover),
        condition=condition,
        frequency=frequency,
        head_noun=head_noun,
        phrases=tuple(phrases_hit),
    )


def normalize_symptom(
    text: str | None, equipment_type: str | None = None, config: ResolverConfig | None = None
) -> str:
    """Deterministic key of a symptom wording: the failure-mode core of `decompose_symptom`."""
    if not text:
        return ""
    return decompose_symptom(text, equipment_type, config).core


def normalize_for_kind(
    raw: str | None,
    kind: str,
    config: ResolverConfig | None = None,
    context: Mapping[str, str | None] | None = None,
    adjudicator: Callable[[str], str | None] | None = None,
) -> Cleaned:
    """The resolver's cleaning step, per kind. equipment / part: `clean_equipment_label()`
    (a part skips the vessel and record steps); parts = EquipmentParts (-> alias.parts). symptom:
    `decompose_symptom()`: key = the failure-mode core, stem = the core with its casing kept,
    position = the unit tokens found, parts = the decomposition (-> alias.parts). `context` is
    the record context (`equipment_type`, `vessel_name`, `maker`, `model`, `serial`); `config`
    the store's ResolverConfig; `adjudicator` the injected translator for non-Latin leftovers."""
    if kind != "symptom":
        ep = clean_equipment_label(raw, context, config, kind=kind, adjudicator=adjudicator)
        return _cleaned(ep, with_parts=True)
    if not raw or not raw.strip():
        return Cleaned(key="", position=None, stem="", expanded=False)
    parts = decompose_symptom(raw, (context or {}).get("equipment_type"), config)
    return Cleaned(
        key=parts.core,
        position=parts.position,
        stem=parts.stem,
        expanded=False,
        parts=parts.as_dict(),
    )


