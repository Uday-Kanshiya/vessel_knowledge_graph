VESSEL_NAMES_HEADER = (
    "# GENERATED by scripts/build_lookup.py — do not edit; re-run the build instead.\n"
    "# The fleet's vessel names: every record's vessel_name plus every vesselName in the casefile\n"
    "# export (so sister ships are in). Used ONLY as a stopword list by the resolver (docs/13 §3):\n"
    "# a label that names a vessel is not an equipment name. vesselName is audit-only everywhere\n"
    "# else (docs/README conventions); this list is its one load-bearing role, as for mail.subject_stem.\n"
)


def iter_records(data_dir: Path, ids: list[str] | None):
    base = data_dir / "extractions"
    if not base.exists():
        return
    for d in sorted(base.iterdir()):
        if ids and d.name not in ids:
            continue
        p = d / "record.json"
        if p.exists():
            with open(p, encoding="utf-8") as fh:
                yield json.load(fh)


def export_vessel_names(export_path: str | Path | None) -> set[str]:
    """Every vesselName in the casefile export (the fleet). Missing / unset export -> empty."""
    if not export_path or not Path(export_path).exists():
        return set()
    with open(export_path, encoding="utf-8") as fh:
        data = json.load(fh)
    raw_list = data["casefiles"] if isinstance(data, dict) else data
    return {str(r.get("vesselName")).strip() for r in raw_list if r.get("vesselName")}


def write_vessel_names(path: Path, names: set[str]) -> int:
    """Regenerate config/vessel_names.txt: one name per line, sorted, with the generated header."""
    clean = sorted({" ".join(n.split()) for n in names if n and n.strip()}, key=str.casefold)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(VESSEL_NAMES_HEADER + "".join(f"{n}\n" for n in clean), encoding="utf-8")
    return len(clean)


def feed(store: LookupStore, records) -> dict[str, int]:
    counts = {"equipment": 0, "part": 0, "symptom": 0, "new_term": 0, "queued": 0}
    for rec in records:
        src = f"casefile:{rec.get('casefile_id', '?')}"
        for e in rec.get("equipment", []):
            # the entry's own vessel / maker / model / serial are stripped from the name (13 §3)
            r = store.resolve(
                e.get("name"), kind="equipment", source=src, context=equipment_context(rec, e)
            )
            if r:
                counts["equipment"] += 1
                counts["new_term"] += r.method == "new_term"
                counts["queued"] += r.method == "queued"
        for a in rec.get("action_logs", []):
            for p in a.get("parts") or []:
                name = p if isinstance(p, str) else (p.get("name") or "")
                r = store.resolve(name, kind="part", source=src)
                if r:
                    counts["part"] += 1
                    counts["new_term"] += r.method == "new_term"
                    counts["queued"] += r.method == "queued"
        for f in rec.get("faults", []):
            # the record's own equipment type is the only equipment wording stripped (13 §8)
            r = store.resolve(
                f.get("symptom"), kind="symptom", source=src, context=fault_context(rec, f)
            )
            if r:
                counts["symptom"] += 1
                counts["new_term"] += r.method == "new_term"
                counts["queued"] += r.method == "queued"
    return counts


def decomposition_stats(store: LookupStore) -> dict:
    """How the symptom wordings came apart (docs/13 §8): split (a component / location /
    modifier was extracted), whole (passed through), with residue (an unmatched tail), queued
    (undecomposed), and the residue tokens with their distinct-casefile counts."""
    rows = [a for a in store.alias_rows("symptom")]
    pend = store.pending("symptom")
    split = whole = with_residue = 0
    tok_cases: dict[str, set[str]] = {}
    for a in rows:
        p = a["parts"] or {}
        if p.get("component") or p.get("location") or p.get("modifiers"):
            split += 1
        else:
            whole += 1
        if p.get("residue"):
            with_residue += 1
        for t in p.get("residue") or []:
            tok_cases.setdefault(t, set()).add(a["source"])
    for q in pend:
        for t in (q.parts or {}).get("residue") or []:
            tok_cases.setdefault(t, set()).add(q.source)
    residue = sorted(((t, len(c)) for t, c in tok_cases.items()), key=lambda kv: (-kv[1], kv[0]))
    return {
        "labels": len(rows) + len([q for q in pend if q.reason == "undecomposed"]),
        "split": split,
        "whole": whole,
        "with_residue": with_residue,
        "queued": sum(1 for q in pend if q.reason == "undecomposed"),
        "residue": residue,
        "residue_casefiles": {t: sorted(c) for t, c in tok_cases.items()},
    }


def queue_candidate_terms(store: LookupStore, min_casefiles: int = 2) -> list[str]:
    """Residue tokens seen in >= `min_casefiles` distinct casefiles are queued once each as
    reason=candidate_term with the casefiles and the table they probably belong in, so the
    tables grow from evidence (docs/13 §8). Returns the tokens queued."""
    stats = decomposition_stats(store)
    out = []
    for tok, n in stats["residue"]:
        if n < min_casefiles:
            continue
        store.queue(
            "symptom",
            tok,
            "candidate_term",
            parts={
                "token": tok,
                "casefiles": stats["residue_casefiles"][tok],
                "propose": "component_terms|location_terms",
            },
            source="build:residue",
        )
        out.append(tok)
    return out


def classify_symptoms(store: LookupStore, links_path: str | Path) -> dict[str, int]:
    """Family assignment for symptom standards: inherited through the reviewed broader_than
    links (validated against the standards present), else keyword rules, else none."""
    links = SymptomLinks(load_symptom_links(links_path))
    links.validate({s.key for s in store.standards(kind="symptom")})
    for w in links.warnings:
        print(f"[lookup] {w}", file=sys.stderr)
    return store.assign_families("symptom", ancestors_of=links.ancestors)


def check_equipment_types(store: LookupStore, records: list[dict]) -> tuple[list, list]:
    """`--check` (docs/13 §6): every non-merged equipment standard that extraction produced must
    have at least one alias whose record entry carries an equipment_type (the type is a view over
    the records, 13 §3; a standard nobody typed cannot be grouped on the lookup page). Returns
    (offenders, seed_only): seed-only standards (no extraction alias at all) are reported, not
    failed — the seed CSV has no type column by design."""
    typed: set[str] = set()
    for rec in records:
        for e in rec.get("equipment", []) or []:
            if (e.get("name") or "").strip() and (e.get("equipment_type") or "").strip():
                typed.add(raw_key_of(e["name"]))
    by_std: dict[int, list[dict]] = {}
    for a in store.alias_rows("equipment"):
        by_std.setdefault(a["standard_id"], []).append(a)
    offenders, seed_only = [], []
    for s in store.standards(kind="equipment"):
        if s.status == "merged":
            continue
        aliases = by_std.get(s.id, [])
        from_records = [a for a in aliases if a["source"].startswith("casefile:")]
        if not from_records:
            seed_only.append(s)
        elif not any(a["raw_key"] in typed for a in from_records):
            offenders.append(s)
    return offenders, seed_only


def promote_row(p) -> str:
    """The seed-CSV line that promotes a pending row: kind,raw_term,standard_key,status[,family_key].
    Fill in <standard_key> (a normalised key or any spelling of the standard)."""
    tail = ",<family_key>" if p.kind == "symptom" else ""
    return f"{p.kind},{p.raw_term},<standard_key>,reviewed{tail}"


def print_review(store: LookupStore) -> None:
    rows = store.review_queue()
    print(f"\nreview queue 1 — auto-minted standards: {len(rows)}")
    if rows:
        print(f"{'id':>4}  {'kind':9} {'display':45} {'hits':>4}  aliases")
        for s in rows:
            print(f"{s.id:>4}  {s.kind:9} {s.display[:45]:45} {s.hits:>4}  {' | '.join(s.aliases)}")
    uncl = store.unclassified("symptom")
    print(f"\nreview queue 2 — symptom standards with no family: {len(uncl)}")
    if uncl:
        print(f"{'id':>4}  {'display':60} {'hits':>4}  fix: kind,raw_term,standard_key,family_key")
        for s in uncl:
            print(
                f"{s.id:>4}  {s.display[:60]:60} {s.hits:>4}  symptom,{s.aliases[0] if s.aliases else s.key},{s.key},<family_key>"
            )
    pend = store.pending()
    print(f"\nreview queue 3 — queued, not minted (pending_term): {len(pend)}")
    if pend:
        print(
            f"{'kind':9} {'raw spelling':45} {'reason':19} {'hits':>4}  {'source':30}  promote: CSV row (or dismiss)"
        )
        for p in pend:
            parts = f"  parts={json.dumps(p.parts, ensure_ascii=False)}" if p.parts else ""
            print(
                f"{p.kind:9} {p.raw_term[:45]:45} {p.reason:19} {p.hit_count:>4}  {p.source[:30]:30}  {promote_row(p)}{parts}"
            )
    print()
    print("review queue 4 — " + render_duplicates(scan_duplicates(store)), end="")


def print_families(store: LookupStore, kind: str = "symptom") -> None:
    fams = store.families(kind)
    std = [s for s in store.standards(kind=kind) if s.status != "merged"]
    by_fam: dict[str | None, list] = {}
    for s in std:
        by_fam.setdefault(s.family_key, []).append(s)
    used = sum(1 for f in fams if by_fam.get(f.key))
    print(
        f"\n{kind} families: {len(fams)} defined, {used} used, {len(by_fam.get(None, []))} standards unclassified"
    )
    for f in fams + [None]:
        key = f.key if f else None
        rows = sorted(by_fam.get(key, []), key=lambda s: (-s.hits, s.key))
        if not rows and f is not None:
            continue
        print(
            f"\n  {(f.display if f else 'unclassified'):30} {len(rows):>3} standards  {sum(s.hits for s in rows):>4} hits"
        )
        for s in rows:
            print(f"      [{s.family_method:9}] {s.display[:70]:70} {s.hits:>3}")


def main(argv=None) -> int:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--data-dir", default=config.EXTRACTION_DATA_DIR)
    p.add_argument("--db", default=config.RESOLUTION_DB_PATH)
    p.add_argument("--ids", nargs="+")
    p.add_argument(
        "--seed", action="append", default=[], help="extra alias CSV(s) to import (human)"
    )
    p.add_argument("--no-seed", action="store_true", help="skip the repo seed CSVs and family list")
    p.add_argument(
        "--links", default=config.SYMPTOM_LINKS_PATH, help="symptom broader_than links JSON"
    )
    p.add_argument(
        "--config-dir",
        default=config.RESOLUTION_CONFIG_DIR,
        help="modifier_terms.csv + vessel_names.txt (default: RESOLUTION_CONFIG_DIR = config/)",
    )
    p.add_argument(
        "--export-file",
        default=config.CASEFILE_EXPORT_PATH or None,
        help="casefile export JSON; its vesselName values go into vessel_names.txt "
        "(default: CASEFILE_EXPORT_PATH; missing = records only)",
    )
    p.add_argument(
        "--no-vessel-names",
        action="store_true",
        help="do not regenerate <config-dir>/vessel_names.txt",
    )
    p.add_argument(
        "--residue-min",
        type=int,
        default=2,
        help="queue a residue token as candidate_term when seen in at least this many casefiles",
    )
    p.add_argument("--export", help="write every alias (with family_key) to this CSV")
    p.add_argument("--review", action="store_true", help="print the three review queues")
    p.add_argument(
        "--check",
        action="store_true",
        help="fail (exit 1) when an equipment standard built from the records has no alias whose "
        "record entry carries an equipment_type",
    )
    p.add_argument("--families", action="store_true", help="print family -> standards -> hits")
    p.add_argument("--fresh", action="store_true", help="delete the DB first")
    args = p.parse_args(argv)

    records = list(iter_records(Path(args.data_dir), args.ids))
    config_dir = Path(args.config_dir)
    if not args.no_vessel_names:
        names = {r.get("vessel_name") or "" for r in records} | export_vessel_names(
            args.export_file
        )
        n = write_vessel_names(config_dir / VESSEL_NAMES_TXT, names)
        print(f"fleet: {n} vessel names -> {config_dir / VESSEL_NAMES_TXT}")

    db = Path(args.db)
    if args.fresh and db.exists():
        db.unlink()
    exit_code = 0
    with LookupStore(db, config_dir=config_dir, guard=DEFAULT_GUARD) as store:
        if not args.no_seed:
            for path, what in (
                (config.SYMPTOM_FAMILIES_CSV, "families"),
                (config.RESOLUTION_SEED_CSV, "aliases"),
                (config.SEED_SYMPTOM_ALIASES_CSV, "aliases"),
            ):
                if Path(path).exists():
                    n = (
                        store.import_families_csv(path, kind="symptom")
                        if what == "families"
                        else store.import_csv(path, source="seed")
                    )
                    print(f"seed: {n} {what} from {path}")
        for extra in args.seed:
            n = store.import_csv(extra, source="human")
            print(f"seed: {n} aliases from {extra}")
        counts = feed(store, records)
        print(
            f"resolved {counts['equipment']} equipment, {counts['part']} part and {counts['symptom']} symptom "
            f"names; {counts['new_term']} new standards minted, {counts['queued']} queued (not minted)"
        )
        cands = queue_candidate_terms(store, args.residue_min)
        st = decomposition_stats(store)
        print(
            f"symptom decomposition: {st['labels']} labels — {st['split']} split, {st['whole']} whole, "
            f"{st['with_residue']} with residue, {st['queued']} queued undecomposed; "
            f"candidate terms queued (>= {args.residue_min} casefiles): {cands or 'none'}"
        )
        if st["residue"]:
            top = ", ".join(f"{t} ({n})" for t, n in st["residue"][:15])
            print(f"  residue tokens (casefiles): {top}")
        for r in retire_dissolved(args.links, store):
            print(
                f"[lookup] retired link {r['broader']!r} > {r['narrower']!r}: {r['rationale']}",
                file=sys.stderr,
            )
        methods = classify_symptoms(store, args.links)
        print("symptom families assigned by method:", methods)
        frag = store.fragmentation()
        print("fragmentation:", {k: v for k, v in frag.items() if k != "by_kind"})
        for k, v in frag["by_kind"].items():
            print(f"  {k:9}", v)
        if args.review:
            print_review(store)
        if args.families:
            print_families(store)
        if args.export:
            n = store.export_csv(args.export)
            print(f"exported {n} aliases to {args.export}")
        if args.check:
            offenders, seed_only = check_equipment_types(store, records)
            print(
                f"check: {len(offenders)} equipment standard(s) without a typed record alias; "
                f"{len(seed_only)} seed-only (not checked)"
            )
            for s in offenders:
                print(f"  #{s.id} {s.display!r} <- {' | '.join(s.aliases)}", file=sys.stderr)
            if offenders:
                exit_code = 1
    print(f"db: {db}")
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
