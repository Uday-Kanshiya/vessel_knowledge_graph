"""
Build / refresh the alias table (equipment, parts, symptoms) from the run store (docs/13).

    python scripts/build_lookup.py                    # seeds + every record under data/ -> lookup.sqlite
    python scripts/build_lookup.py --ids ID [ID ...]  # a subset of casefiles
    python scripts/build_lookup.py --review           # the three review queues: auto-minted standards,
                                                      # symptom standards with no family, queued (not minted)
    python scripts/build_lookup.py --families         # family -> standards -> hits
    python scripts/build_lookup.py --export out.csv   # dump every alias (with family_key) for editing
    python scripts/build_lookup.py --seed my.csv      # load an extra human-edited CSV (wins over rules)
    python scripts/build_lookup.py --fresh            # delete the SQLite file first and rebuild
    python scripts/build_lookup.py --db /tmp/new.sqlite --fresh   # a candidate for scripts/diff_lookup.py

Order of operations: fleet list (config/vessel_names.txt, regenerated from the records' vessel_name
and the export's vesselName) -> family list (config/symptom_families.csv) -> seed aliases (equipment:
src/resolution/seed_aliases.csv, symptom: config/seed_symptom_aliases.csv) -> every record's
equipment[].name, action_logs[].parts[], faults[].symptom -> family assignment for symptoms
(human/seed rows kept; inherited via config/symptom_links.json, else keyword rules, else none).

Idempotent: re-run after every extraction run. Order of input does not change the result
(the standard key is a function of the text). Nothing here writes to a record. Every seed /
config CSV is header-checked at import: a wrong header fails the build.
"""

